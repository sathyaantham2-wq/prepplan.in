"""Merge batch tags into content/authoring/civil/polity/polity-tagged.json and validate. Internal tooling."""
import json, glob, collections, re, sys
base = 'content/authoring/civil/polity/'
src = {q['id']: q for q in json.load(open('content/reference/civil-services/polity-pyq-merged.json'))}
ENUM = dict(
  scope={'polity','adjacent','out'},
  format={'direct','statements_which','statements_count','statement_I_II','match','assertion','case_study','other'},
  source_type={'static_text','judgement','amendment_act','current_affairs','committee_report','convention','other'},
  skill={'recall','two_step','elimination','application'},
  answer_check={'agrees','disagrees','not_in_laxmikanth','cancelled','conflict_unresolved'})
tags = {}; errs = []
for f in sorted(glob.glob(base + 'tags/batch*.json')):
    for t in json.load(open(f)):
        if t['id'] in tags: errs.append(('dup tag', t['id']))
        tags[t['id']] = t
for i in src:
    if i not in tags: errs.append(('missing', i))
for i, t in tags.items():
    if i not in src: errs.append(('unknown id', i)); continue
    for k, ok in ENUM.items():
        if t.get(k) not in ok: errs.append((k, i, t.get(k)))
    for k in ('articles', 'concepts', 'traps'):
        if not isinstance(t.get(k), list): errs.append((k, i))
    lk = t.get('laxmikanth') or {}
    ch = lk.get('chapter')
    if ch is not None and not (isinstance(ch, int) and 1 <= ch <= 95): errs.append(('chapter', i, ch))
    if t['answer_check'] != 'agrees' and not t.get('notes'): errs.append(('notes needed', i))
print('errors:', len(errs)); [print(' ', e) for e in errs[:30]]
# duplicates by stem
def n(s): return re.sub(r'[^a-z0-9]', '', s.lower())[:90]
seen = collections.defaultdict(list)
for i, q in src.items(): seen[n(q['stem'] + ''.join(q['options'].values()))].append(i)
dups = [v for v in seen.values() if len(v) > 1]
merged = []
dupmap = {x: v[0] for v in dups for x in v[1:]}
for i, q in src.items():
    t = tags.get(i, {})
    r = {**q, **{k: v for k, v in t.items() if k != 'id'}}
    r['duplicate_of'] = dupmap.get(i)
    merged.append(r)
json.dump(merged, open(base + 'polity-tagged.json', 'w'), ensure_ascii=False, indent=1)
c = collections.Counter
print('total', len(merged), 'dups', dups)
print(c(m.get('scope') for m in merged)); print(c(m.get('answer_check') for m in merged))
bad = [m for m in merged if m.get('answer_check') in ('disagrees', 'conflict_unresolved', 'cancelled') or 'answer_conflict' in m]
print('issue items', len(bad))
with open(base + 'ISSUES.md', 'w') as f:
    f.write('# Polity PYQ - items where the stored key needs a human decision\n\nGenerated by merge-polity-tags.py from tagger notes. Taggers\' opinions, NOT verdicts: nothing here changes a key. Check against the official UPSC key (Laxmikanth 8e prints the papers in ch95, pdf pages ~1095-1135).\n\n')
    for m in bad:
        f.write(f"## {m['id']} - stored key ({m['answer']}) - {m.get('answer_check')}\n")
        if 'answer_conflict' in m: f.write(f"- source conflict: {m['answer_conflict']}\n")
        f.write(f"- {m['stem'][:160].replace(chr(10),' ')}\n- tagger: {m.get('notes','')}\n\n")
